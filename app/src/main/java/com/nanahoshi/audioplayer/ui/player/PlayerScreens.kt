class PlayerViewModel(app: Application) : AndroidViewModel(app) {
    private val graph = app.graph()
    val state = graph.player.state
    val queue = graph.library.observeQueue()
    val client = graph.player
    var subtitleCues by mutableStateOf<List<SubtitleCue>>(emptyList())
        private set
    var generatedEmpty by mutableStateOf(false)
        private set
    var fromGenerated by mutableStateOf(false)
        private set
    var subtitlesReady by mutableStateOf(false)
        private set
    var showChinese by mutableStateOf(true)
    var offerBiliCache by mutableStateOf(false)
        private set
    var translating by mutableStateOf(false)
        private set
    var polishing by mutableStateOf(false)
        private set
    internal var whisperPrompt by mutableStateOf<WhisperPrompt?>(null)
        private set
    internal var translatePrompt by mutableStateOf(false)
        private set
    private var generateWithTranslation = false

    init {
        viewModelScope.launch {
            while (isActive) {
                client.publishNow()
                delay(400)
            }
        }
        viewModelScope.launch {
            client.state.map { it.queueItemId }.distinctUntilChanged().collectLatest { queueItemId ->
                subtitleCues = emptyList()
                generatedEmpty = false
                fromGenerated = false
                subtitlesReady = false
                showChinese = true
                reloadSubtitles(queueItemId)
                offerBiliCache = biliNeedsCache(queueItemId)
            }
        }
        viewModelScope.launch {
            graph.whisper.observe()
                .map { jobs -> jobs.filter { it.status == DownloadStatus.DONE }.map { it.id to it.translatedAt } }
                .distinctUntilChanged()
                .collectLatest { reloadSubtitles(client.state.value.queueItemId) }
        }
        viewModelScope.launch {
            graph.translator.updates.collectLatest {
                reloadSubtitles(client.state.value.queueItemId)
            }
        }
    }

    fun dismissWhisperPrompt() {
        whisperPrompt = null
    }

    fun dismissTranslatePrompt() {
        translatePrompt = false
    }

    fun generateNeedsLocalNetwork(): Boolean {
        val whisperBase = effectiveWhisperBase(
            graph.credentials.resolvedWhisperModel(),
            graph.credentials.whisperBaseUrl(),
        )
        return isLocalNetworkAddress(whisperBase)
    }

    fun reportLocalNetworkDenied() {
        graph.messages.value = "需要允许访问本地网络，才能连接这台设备"
    }

    fun requestTranslation() {
        viewModelScope.launch {
            if (!graph.credentials.hasTranslate()) {
                translatePrompt = true
                return@launch
            }
            if (translating) return@launch
            val row = currentRow() ?: return@launch
            translating = true
            try {
                val translated = graph.translator.translateRow(row)
                if (translated) {
                    showChinese = true
                    reloadSubtitles(client.state.value.queueItemId)
                } else {
                    graph.messages.value = "翻译失败"
                }
            } catch (cancelled: CancellationException) {
                if (!isActive) throw cancelled
            } finally {
                translating = false
            }
        }
    }

    fun cancelTranslation() {
        viewModelScope.launch {
            val row = currentRow() ?: return@launch
            graph.translator.cancelRow(row)
        }
    }

    fun requestPolish() {
        viewModelScope.launch {
            if (!graph.credentials.hasTranslate()) {
                translatePrompt = true
                return@launch
            }
            if (polishing) return@launch
            val row = currentRow() ?: return@launch
            polishing = true
            try {
                val polished = graph.translator.polishRow(row)
                if (polished) {
                    showChinese = true
                    reloadSubtitles(client.state.value.queueItemId)
                } else {
                    graph.messages.value = "润色失败，已保留原译文"
                }
            } catch (cancelled: CancellationException) {
                if (!isActive) throw cancelled
            } finally {
                polishing = false
            }
        }
    }

    fun cancelPolish() {
        viewModelScope.launch {
            val row = currentRow() ?: return@launch
            graph.translator.cancelPolish(row)
        }
    }

    fun cacheCurrent() {
        viewModelScope.launch {
            val row = currentRow() ?: return@launch
            val bvid = row.bvid ?: return@launch
            val cid = row.cid ?: return@launch
            val added = if (row.trackId != null && row.trackId > 0L) {
                val track = graph.db.tracks().getById(row.trackId)
                if (track != null) graph.downloads.enqueue(listOf(track)) else 0
            } else {
                graph.downloads.enqueueBili(
                    listOf(
                        com.nanahoshi.audioplayer.bilibili.BiliPart(
                            bvid = bvid,
                            cid = cid,
                            page = row.page ?: 1,
                            title = row.title,
                            artist = row.artist.orEmpty(),
                            durationMs = row.durationMs,
                            coverUrl = row.coverUri.orEmpty(),
                        ),
                    ),
                )
            }
            offerBiliCache = false
            graph.messages.value = if (added == 0) "已经在本地或正在缓存" else "已加入缓存"
        }
    }

    private suspend fun biliNeedsCache(queueItemId: Long): Boolean {
        val row = graph.library.queueSnapshot().find { it.queueItemId == queueItemId } ?: return false
        if (row.source != com.nanahoshi.audioplayer.data.TrackSource.BILIBILI) return false
        val path = row.localUri
        if (!path.isNullOrBlank() && path.startsWith("/") && java.io.File(path).isFile) return false
        return com.nanahoshi.audioplayer.data.readyBiliAudio(
            getApplication<Application>().filesDir,
            row.bvid,
            row.cid,
        ) == null
    }

    fun requestGenerate(translate: Boolean) {
        viewModelScope.launch {
            if (!graph.credentials.hasWhisper()) {
                whisperPrompt = WhisperPrompt.NeedSettings
                return@launch
            }
            generateWithTranslation = translate
            val row = currentRow() ?: return@launch
            val file = graph.whisper.existingFile(row)
            if (file != null) {
                report(graph.whisper.start(row, file, translate), translate)
                return@launch
            }
            val canDownload = row.source == TrackSource.ASMR || row.source == TrackSource.DLSITE
            val hasTarget = (row.trackId != null && row.trackId > 0L) || !row.remoteUrl.isNullOrBlank()
            if (canDownload && hasTarget) {
                whisperPrompt = WhisperPrompt.NeedDownload
                return@launch
            }
            graph.messages.value = "这首无法下载，不能生成字幕"
        }
    }

    fun discardSubtitles() {
        viewModelScope.launch {
            val row = currentRow() ?: return@launch
            graph.subtitles.discard(row)
            reloadSubtitles(client.state.value.queueItemId)
        }
    }

    fun confirmWhisperDownload() {
        whisperPrompt = null
        val translate = generateWithTranslation
        viewModelScope.launch {
            val row = currentRow() ?: return@launch
            report(graph.whisper.startAfterDownload(row, translate), translate)
        }
    }

    private suspend fun currentRow() =
        graph.library.queueSnapshot().find { it.queueItemId == client.state.value.queueItemId }

    private suspend fun reloadSubtitles(queueItemId: Long) {
        if (queueItemId <= 0L) {
            fromGenerated = false
            subtitlesReady = true
            return
        }
        val row = graph.library.queueSnapshot().find { it.queueItemId == queueItemId }
        if (row == null) {
            if (client.state.value.queueItemId == queueItemId) {
                fromGenerated = false
                subtitlesReady = true
            }
            return
        }
        val loaded = graph.subtitles.load(row)
        if (client.state.value.queueItemId != queueItemId) return
        subtitleCues = loaded.cues
        generatedEmpty = loaded.generatedEmpty
        fromGenerated = loaded.generated
        subtitlesReady = true
    }

    private suspend fun report(result: WhisperStart, translate: Boolean) {
        when (result) {
            WhisperStart.Started -> graph.messages.value =
                if (translate) "已开始生成字幕和翻译" else "已开始生成字幕"
            WhisperStart.AlreadyRunning -> graph.messages.value = "已经在生成字幕"
            WhisperStart.AlreadyDone -> {
                reloadSubtitles(client.state.value.queueItemId)
                if (translate) translateExisting()
            }
            WhisperStart.Unavailable -> graph.messages.value = "这首无法下载，不能生成字幕"
        }
    }

    private suspend fun translateExisting() {
        val row = currentRow() ?: return
        val cues = graph.subtitles.load(row).cues
        if (cues.isEmpty() || cues.hasTranslation()) return
        if (!graph.credentials.hasTranslate()) {
            translatePrompt = true
            return
        }
        if (translating) return
        translating = true
        try {
            val translated = graph.translator.translateRow(row)
            if (translated) {
                showChinese = true
                reloadSubtitles(client.state.value.queueItemId)
            } else {
                graph.messages.value = "翻译失败"
            }
        } catch (cancelled: CancellationException) {
            if (!coroutineContext.isActive) throw cancelled
        } finally {
            translating = false
        }
    }
}

internal enum class WhisperPrompt {
    NeedSettings,
    NeedDownload,
}

@Composable
fun MiniPlayer(onOpen: () -> Unit, viewModel: PlayerViewModel = viewModel()) {
    val state by viewModel.state.collectAsStateWithLifecycle()
    if (!state.hasMedia) return
    Column(Modifier.clickable(onClick = onOpen).fillMaxWidth()) {
        val progress = if (state.durationMs > 0) state.positionMs / state.durationMs.toFloat() else 0f
        LinearProgressIndicator(progress = { progress.coerceIn(0f, 1f) }, modifier = Modifier.fillMaxWidth())
        ListItem(
            headlineContent = { Text(state.title.ifBlank { "正在播放" }, maxLines = 1, overflow = TextOverflow.Ellipsis) },
            supportingContent = { Text(state.artist, maxLines = 1, overflow = TextOverflow.Ellipsis) },
            leadingContent = { CoverImage(state.coverUri) },
            trailingContent = {
                IconButton(onClick = viewModel.client::toggle) {
                    Icon(
                        if (state.isPlaying) Icons.Default.Pause else Icons.Default.PlayArrow,
                        contentDescription = if (state.isPlaying) "暂停" else "播放",
                    )
                }
            },
        )
    }
}

@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun NowPlayingScreen(onBack: () -> Unit, viewModel: PlayerViewModel = viewModel()) {
    val state by viewModel.state.collectAsStateWithLifecycle()
    val queue by viewModel.queue.collectAsStateWithLifecycle(emptyList())
    val remaining by viewModel.client.sleepRemainingMs.collectAsStateWithLifecycle()
    var sleepDialog by remember { mutableStateOf(false) }
    var queueExpanded by remember { mutableStateOf(false) }
    val listState = rememberLazyListState()
    val reorderState = rememberReorderableLazyListState(listState) { from, to ->
        viewModel.client.move(from.index, to.index)
    }
    val subtitleScroll = rememberScrollState()
    val cues = viewModel.subtitleCues
    val subtitle = cues.textAt(state.positionMs, viewModel.showChinese)
    var showSubtitles by remember { mutableStateOf(false) }
    var discardPrompt by remember { mutableStateOf(false) }
    val localNetwork = rememberLocalNetworkAccess { viewModel.reportLocalNetworkDenied() }
    LaunchedEffect(subtitle) { subtitleScroll.scrollTo(0) }
    WhisperPromptDialog(viewModel)
    if (discardPrompt) {
        AlertDialog(
            onDismissRequest = { discardPrompt = false },
            text = { Text("删除这首的字幕？可以之后重新生成。") },
            confirmButton = {
                TextButton(onClick = {
                    discardPrompt = false
                    showSubtitles = false
                    viewModel.discardSubtitles()
                }) { Text("删除") }
            },
            dismissButton = {
                TextButton(onClick = { discardPrompt = false }) { Text("取消") }
            },
        )
    }
    if (showSubtitles) {
        SubtitleReader(
            cues = cues,
            positionMs = state.positionMs,
            chinese = viewModel.showChinese,
            translating = viewModel.translating,
            canDelete = viewModel.fromGenerated,
            onChinese = { viewModel.showChinese = true },
            onJapanese = { viewModel.showChinese = false },
            onTranslate = viewModel::requestTranslation,
            onStop = viewModel::cancelTranslation,
            polishing = viewModel.polishing,
            onPolish = viewModel::requestPolish,
            onStopPolish = viewModel::cancelPolish,
            onDelete = { discardPrompt = true },
            onSeek = viewModel.client::seekTo,
            onBack = { showSubtitles = false },
        )
        return
    }
    Column(Modifier.fillMaxSize().padding(16.dp)) {
        Row(verticalAlignment = Alignment.CenterVertically) {
            IconButton(onClick = onBack) {
                Icon(Icons.AutoMirrored.Filled.ArrowBack, contentDescription = "返回")
            }
            if (queueExpanded) {
                TextButton(onClick = { viewModel.client.clearQueue() }) { Text("清空") }
                TextButton(onClick = { queueExpanded = false }) { Text("恢复") }
            }
        }
        if (!state.hasMedia) {
            EmptyHint("当前没有在播的音频。从音频库点一首，或播放一个列表。")
            return
        }
        if (!queueExpanded) {
            CoverImage(state.coverUri, Modifier.size(160.dp).align(Alignment.CenterHorizontally))
            Text(state.title, style = MaterialTheme.typography.headlineSmall, modifier = Modifier.padding(top = 16.dp))
            Text(state.artist, color = MaterialTheme.colorScheme.onSurfaceVariant)
            if (viewModel.offerBiliCache) {
                TextButton(
                    onClick = viewModel::cacheCurrent,
                    modifier = Modifier.align(Alignment.CenterHorizontally),
                ) { Text("缓存音轨") }
            }
            Box(
                modifier = Modifier
                    .weight(1f)
                    .fillMaxWidth()
                    .then(
                        if (cues.isNotEmpty()) {
                            Modifier.clickable { showSubtitles = true }
                        } else {
                            Modifier
                        },
                    ),
                contentAlignment = Alignment.Center,
            ) {
                when {
                    subtitle.isNotEmpty() -> Text(
                        subtitle,
                        textAlign = TextAlign.Center,
                        modifier = Modifier
                            .fillMaxWidth()
                            .verticalScroll(subtitleScroll)
                            .pointerInput(Unit) {
                                detectTapGestures(onTap = { showSubtitles = true })
                            },
                    )
                    cues.isNotEmpty() -> Unit
                    viewModel.generatedEmpty -> Column(horizontalAlignment = Alignment.CenterHorizontally) {
                        Text(
                            "没有听出人声",
                            textAlign = TextAlign.Center,
                            color = MaterialTheme.colorScheme.onSurfaceVariant,
                        )
                        TextButton(onClick = { discardPrompt = true }) { Text("删除字幕") }
                    }
                    viewModel.subtitlesReady -> Row(
                        Modifier.fillMaxWidth(),
                        horizontalArrangement = Arrangement.Center,
                        verticalAlignment = Alignment.CenterVertically,
                    ) {
                        TextButton(onClick = {
                            localNetwork.run(viewModel.generateNeedsLocalNetwork()) {
                                viewModel.requestGenerate(translate = true)
                            }
                        }) {
                            Text("生成字幕和翻译")
                        }
                        TextButton(onClick = {
                            localNetwork.run(viewModel.generateNeedsLocalNetwork()) {
                                viewModel.requestGenerate(translate = false)
                            }
                        }) {
                            Text("生成字幕")
                        }
                    }
                }
            }
            SeekBar(state, onSeek = viewModel.client::seekTo)
            Row(Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.Center) {
                IconButton(onClick = viewModel.client::previous) {
                    Icon(Icons.Default.SkipPrevious, contentDescription = "上一首")
                }
                IconButton(onClick = viewModel.client::toggle) {
                    Icon(
                        if (state.isPlaying) Icons.Default.Pause else Icons.Default.PlayArrow,
                        contentDescription = if (state.isPlaying) "暂停" else "播放",
                    )
                }
                IconButton(onClick = viewModel.client::next) {
                    Icon(Icons.Default.SkipNext, contentDescription = "下一首")
                }
            }
            SleepTimerRow(
                remainingMs = remaining,
                onOpen = { sleepDialog = true },
                onCancel = viewModel.client::cancelSleepTimer,
            )
            if (sleepDialog) {
                SleepTimerDialog(
                    onDismiss = { sleepDialog = false },
                    onStart = { totalMs ->
                        viewModel.client.startSleepTimer(totalMs)
                        sleepDialog = false
                    },
                )
            }
            TextButton(onClick = { queueExpanded = true }) { Text("播放列表") }
        } else {
        LazyColumn(state = listState, modifier = Modifier.weight(1f).fillMaxWidth()) {
            itemsIndexed(queue, key = { _, item -> item.queueItemId }) { index, item ->
                ReorderableItem(reorderState, key = item.queueItemId) {
                    val current = item.queueItemId == state.queueItemId
                    ListItem(
                        headlineContent = { Text(item.title) },
                        supportingContent = { Text(item.artist.orEmpty()) },
                        leadingContent = {
                            Icon(Icons.Default.DragHandle, contentDescription = "拖动排序", modifier = Modifier.draggableHandle())
                        },
                        trailingContent = {
                            IconButton(onClick = { viewModel.client.remove(index, item.queueItemId) }) {
                                Icon(Icons.Default.Delete, contentDescription = "从当前列表移除")
                            }
                        },
                        modifier = Modifier.clickable {
                            viewModel.client.playQueueItem(item.queueItemId)
                        },
                        colors = if (current) {
                            androidx.compose.material3.ListItemDefaults.colors(
                                containerColor = MaterialTheme.colorScheme.secondaryContainer,
                            )
                        } else {
                            androidx.compose.material3.ListItemDefaults.colors()
                        },
                    )
                }
            }
        }
        }
    }
}

@Composable
private fun SubtitleReader(
    cues: List<SubtitleCue>,
    positionMs: Long,
    chinese: Boolean,
    translating: Boolean,
    canDelete: Boolean,
    onChinese: () -> Unit,
    onJapanese: () -> Unit,
    onTranslate: () -> Unit,
    onStop: () -> Unit,
    polishing: Boolean,
    onPolish: () -> Unit,
    onStopPolish: () -> Unit,
    onDelete: () -> Unit,
    onSeek: (Long) -> Unit,
    onBack: () -> Unit,
) {
    BackHandler(onBack = onBack)
    val listState = rememberLazyListState()
    val active = cues.indexAt(positionMs)
    val blue = if (isSystemInDarkTheme()) Color(0xFF90CAF9) else Color(0xFF1565C0)
    var placed by remember { mutableStateOf(false) }
    LaunchedEffect(active, cues.size) {
        if (active < 0 || cues.isEmpty()) return@LaunchedEffect
        listState.centerOn(active, animated = placed)
        if (!placed) {
            placed = true
            listState.centerOn(active, animated = false)
        }
    }
    Column(Modifier.fillMaxSize()) {
        Row(Modifier.fillMaxWidth(), verticalAlignment = Alignment.CenterVertically) {
            IconButton(onClick = onBack) {
                Icon(Icons.AutoMirrored.Filled.ArrowBack, contentDescription = "返回")
            }
            Text("字幕", style = MaterialTheme.typography.titleLarge, modifier = Modifier.weight(1f))
            if (cues.hasTranslation()) {
                TextButton(onClick = onChinese) {
                    Text("中文", color = if (chinese) MaterialTheme.colorScheme.primary else MaterialTheme.colorScheme.onSurfaceVariant)
                }
                TextButton(onClick = onJapanese) {
                    Text("日文", color = if (!chinese) MaterialTheme.colorScheme.primary else MaterialTheme.colorScheme.onSurfaceVariant)
                }
                if (polishing) {
                    TextButton(onClick = onStopPolish) { Text("中止") }
                } else {
                    TextButton(onClick = onPolish) { Text("润色") }
                }
            } else if (cues.isNotEmpty()) {
                if (translating) {
                    TextButton(onClick = onStop) { Text("中止") }
                } else {
                    TextButton(onClick = onTranslate) { Text("生成翻译") }
                }
            }
            if (canDelete) {
                TextButton(onClick = onDelete) { Text("删除") }
            }
        }
        if (cues.isEmpty()) {
            EmptyHint("这首没有字幕")
        } else {
        LazyColumn(state = listState, modifier = Modifier.weight(1f).fillMaxWidth()) {
            itemsIndexed(cues, key = { index, cue -> "$index-${cue.startMs}" }) { index, cue ->
                val current = index == active
                Text(
                    cue.line(chinese),
                    color = if (current) blue else MaterialTheme.colorScheme.onSurface,
                    fontWeight = if (current) FontWeight.SemiBold else FontWeight.Normal,
                    textAlign = TextAlign.Center,
                    modifier = Modifier
                        .fillMaxWidth()
                        .clickable { onSeek(cue.startMs) }
                        .padding(horizontal = 24.dp, vertical = 12.dp),
                )
            }
        }
        }
    }
}

private suspend fun LazyListState.centerOn(index: Int, animated: Boolean) {
    val viewport = (layoutInfo.viewportEndOffset - layoutInfo.viewportStartOffset).coerceAtLeast(0)
    val sample = layoutInfo.visibleItemsInfo.firstOrNull()?.size ?: 0
    val offset = if (viewport > 0 && sample > 0) -((viewport - sample) / 2) else 0
    if (animated) animateScrollToItem(index, offset) else scrollToItem(index, offset)
}

